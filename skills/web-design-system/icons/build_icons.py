#!/usr/bin/env python3
"""Build an app's icons.js from icon sources in the shared faceted style (skills/web-design-system).

Adapted from Camp de Base (ac-ua/Base-Camp, scripts/build_icons.py). Standard library only.

Sources (JSON), merged in order (a later file adds icons or overrides one of the same name):
  icons.json   {name: {label, parts: [[path, role]], lines: [[path, on_facet]]}}, 24 x 24 grid
               role: a = sky, b = slate, c = snow, d = stone (CSS variables --ci-a … --ci-d), "#rrggbb" = a fixed fill
               with the outline, "!#rrggbb" = a flat fill without outline (illustrations only). Outline 1.3, always dark
               (--ci-ink). lines: detail strokes; on_facet 1 = drawn on a facet (dark), 0 = free (text colour).
  glyphs.json  {name: {label, svg}}: plain UI control glyphs (menu, close, search…), stroke 2, currentColor.
  emoji map    optional {emoji: icon_name}: replaces leftover emojis in pages (migration aid).

Usage:
  python3 build_icons.py                                   # kit only → icons.js next to this script
  python3 build_icons.py --src <brain>/skills/web-design-system/icons/icons.json --src data/icons.app.json \\
      --glyphs <brain>/skills/web-design-system/icons/glyphs.json --global SportIcons --out web/icons.js
  python3 build_icons.py --sheet /tmp/icons.html           # also a preview sheet (16/24/48 px, light and dark)
  python3 build_icons.py --check                           # validate only, write nothing

In pages: load icons.js, then write :ci-name: in any text (rendered as the icon), or call
<Global>.svg("name"), <Global>.svgAt("name", x, y, size) inside an SVG drawing, <Global>.glyph("search").
"""
import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
NAME = re.compile(r"^[a-z0-9_]+$")
ROLE = re.compile(r"^(?:[abcd]|!?#[0-9a-fA-F]{6})$")
VERBOSE = False
NUM = re.compile(r"-?\d*\.?\d+")
MAX_FACETS = 4      # the norm: 2 to 4 main facets
MAX_PARTS = 7       # with small parts (wheels, windows, handles); above this, redraw

JS = r"""// __GLOBAL__ · icons (generated by build_icons.py from the design-system kit: do not edit by hand).
// Faceted icons: __GLOBAL__.svg(name), __GLOBAL__.svgAt(name, x, y, size) inside an SVG drawing; text tokens
// ":__PREFIX__-name:" are replaced by the icon as the page renders (stripped in <option>, <title> and attributes).
// UI glyphs: __GLOBAL__.glyph(name). Colours come from the design-system tokens (--ci-ink, --ci-a … --ci-d).
(() => {
  const D = __DATA__;
  const G = __GLYPHS__;
  const EMOJI = __EMOJI__;
  const F = { a: "var(--ci-a, #5b8fc0)", b: "var(--ci-b, #3e5d75)", c: "var(--ci-c, #ffffff)", d: "var(--ci-d, #9ea2ab)" };
  const INK = "var(--ci-ink, #0d1117)";
  const css = document.createElement("style");
  css.textContent = `svg.ci { display: inline-block; width: 1.25em; height: 1.25em; vertical-align: -.28em; overflow: visible; flex: none; }
.ico > svg.ci, .ic > svg.ci { width: 20px; height: 20px; vertical-align: middle; }
svg.ds-glyph { width: 18px; height: 18px; fill: none; stroke: currentColor; flex: none; }`;
  document.head.appendChild(css);
  const body = (ic) => ic.p.map(([d, r]) => r && r[0] === "!" ? `<path d="${d}" fill="${r.slice(1)}"/>`
    : `<path d="${d}" fill="${F[r] || (r && r[0] === "#" ? r : "none")}" stroke="${INK}" stroke-width="1.3" stroke-linejoin="round"/>`).join("")
    + ic.l.map(([d, o]) => `<path d="${d}" fill="none" stroke="${o ? INK : "currentColor"}" stroke-width="1.3" stroke-linecap="round" stroke-linejoin="round"/>`).join("");
  const svg = (name, cls = "") => { const ic = D[name]; return ic ? `<svg class="ci ${cls}" viewBox="0 0 24 24" aria-hidden="true">${body(ic)}</svg>` : ""; };
  const svgAt = (name, x, y, size = 16) => { const ic = D[name]; return ic ? `<svg class="ci-at" x="${x - size / 2}" y="${y - size / 2}" width="${size}" height="${size}" viewBox="0 0 24 24">${body(ic)}</svg>` : ""; };
  const glyph = (name, cls = "") => { const g = G[name]; return g ? `<svg class="ds-glyph ${cls}" viewBox="0 0 24 24" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${g}</svg>` : ""; };
  const TOK = ":__PREFIX__-";
  const nameOf = (s) => (s.startsWith(TOK) ? s.slice(TOK.length, -1) : EMOJI[s.replace(/️/g, "")]);
  const keys = Object.keys(EMOJI).sort((a, b) => b.length - a.length).map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  const RE = new RegExp(`:__PREFIX__-[a-z0-9_]+:${keys.length ? `|(?:${keys.join("|")})\\uFE0F?` : ""}`, "gu");
  const has = (s) => { RE.lastIndex = 0; return RE.test(s); };
  const SKIP = new Set(["SCRIPT", "STYLE", "TEXTAREA", "INPUT", "CODE", "PRE"]);
  const STRIP = new Set(["OPTION", "TITLE"]);
  function fixText(t) {
    const p = t.parentNode;
    if (!p || SKIP.has(p.nodeName) || p.closest?.("[data-noicons]")) return;
    const s = t.nodeValue;
    if (!has(s)) return;
    if (STRIP.has(p.nodeName) || p.namespaceURI === "http://www.w3.org/2000/svg") { t.nodeValue = s.replace(RE, "").replace(/^\s+/, ""); return; }
    const frag = document.createDocumentFragment(); let last = 0;
    s.replace(RE, (m, i) => {
      if (i > last) frag.appendChild(document.createTextNode(s.slice(last, i)));
      const n = nameOf(m);
      if (n && D[n]) { const tpl = document.createElement("template"); tpl.innerHTML = svg(n); frag.appendChild(tpl.content.firstChild); }
      last = i + m.length; return m;
    });
    if (last < s.length) frag.appendChild(document.createTextNode(s.slice(last)));
    p.replaceChild(frag, t);
  }
  const ATTRS = ["title", "aria-label", "label", "placeholder"];
  function fixAttrs(el) { for (const a of ATTRS) { const v = el.getAttribute?.(a); if (v && has(v)) el.setAttribute(a, v.replace(RE, "").replace(/^\s+/, "")); } }
  function fix(root) {
    if (root.nodeType === 3) return fixText(root);
    if (root.nodeType !== 1 || SKIP.has(root.nodeName)) return;
    fixAttrs(root);
    root.querySelectorAll?.("[title],[aria-label],[label],[placeholder]").forEach(fixAttrs);
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT), list = [];
    while (w.nextNode()) list.push(w.currentNode);
    list.forEach(fixText);
  }
  let busy = false;
  const obs = new MutationObserver((ms) => {
    if (busy) return; busy = true;
    try { for (const m of ms) { if (m.type === "characterData") fixText(m.target); else m.addedNodes.forEach(fix); if (m.type === "attributes") fixAttrs(m.target); } } finally { busy = false; }
  });
  const start = () => { fix(document.body); if (has(document.title)) document.title = document.title.replace(RE, "").trim();
    obs.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS }); };
  if (document.body) start(); else document.addEventListener("DOMContentLoaded", start);
  window.__GLOBAL__ = { svg, svgAt, glyph, names: Object.keys(D), glyphs: Object.keys(G), emoji: EMOJI };
})();
"""

SHEET = """<!doctype html><html lang="en"><head><meta charset="utf-8"><title>__GLOBAL__ · icon sheet</title>
<link rel="stylesheet" href="__TOKENS__"><style>
body { padding: 24px; } .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(150px, 1fr)); gap: 10px; }
.cell { background: var(--surface); border: 1px solid var(--line); border-radius: 10px; padding: 10px; display: grid; gap: 6px; }
.row { display: flex; gap: 10px; align-items: end; } .cell small { color: var(--muted); font: 11px var(--mono); }
.dark { margin-top: 24px; padding: 16px; border-radius: 12px; }
</style></head><body><h1>__GLOBAL__ · __COUNT__ icons</h1><p class="ds-muted">16, 24 and 48 px. Light theme, then dark.</p>
<div class="grid">__CELLS__</div><div class="dark" data-theme="dark" style="background:#0b1218">
<div class="grid" style="--surface:#121c24;--line:#22323e;--muted:#92a5b4;--ci-ink:#05080b;color:#eef4f9">__CELLS__</div></div>
<h2 style="margin-top:24px">Glyphs</h2><div class="row">__GLYPHS__</div>
<script src="__JS__"></script></body></html>
"""


def load(path):
    try:
        return json.loads(Path(path).read_text())
    except (OSError, json.JSONDecodeError) as e:
        raise SystemExit(f"{path}: {e}")


def validate(icons, glyphs, emoji):
    errors, warnings, notes = [], [], []
    for name, ic in icons.items():
        where = f"icon {name!r}"
        if not NAME.match(name):
            errors.append(f"{where}: name must be lowercase letters, digits, underscores")
        if not isinstance(ic.get("label"), str) or not ic["label"].strip():
            errors.append(f"{where}: missing label")
        parts, lines = ic.get("parts"), ic.get("lines", [])
        if not isinstance(parts, list) or not parts:
            errors.append(f"{where}: needs at least one facet in parts")
            continue
        for d, role in parts:
            if not ROLE.match(str(role)):
                errors.append(f"{where}: role {role!r} (use a, b, c, d, #rrggbb or !#rrggbb)")
        for d, on in lines:
            if on not in (0, 1):
                errors.append(f"{where}: line flag must be 0 or 1")
        for d in [p[0] for p in parts] + [l[0] for l in lines]:
            if not str(d).strip().upper().startswith("M"):
                errors.append(f"{where}: path must start with M: {d[:30]}")
            # Absolute coordinates only make sense on the grid; relative arcs (a/l) may be negative.
            for n in NUM.findall(d):
                if float(n) > 25 or float(n) < -25:
                    errors.append(f"{where}: coordinate {n} is off the 24 x 24 grid")
                    break
        outlined = [r for _, r in parts if not str(r).startswith("!")]
        if len(outlined) > MAX_PARTS:
            warnings.append(f"{where}: {len(outlined)} facets (2 to {MAX_FACETS} main facets, {MAX_PARTS} at most with small parts; redraw)")
        elif len(outlined) > MAX_FACETS:
            notes.append(f"{name} ({len(outlined)})")
    for name, g in glyphs.items():
        if not NAME.match(name) or not isinstance(g, dict) or "<" not in g.get("svg", ""):
            errors.append(f"glyph {name!r}: expected {{label, svg}} with SVG markup")
    missing = sorted({v for v in emoji.values() if v not in icons})
    if missing:
        errors.append(f"emoji map points to icons that don't exist: {missing}")
    if notes and VERBOSE:
        warnings.append(f"check at 16 px (more than {MAX_FACETS} facets): {', '.join(notes)}")
    return errors, warnings


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--src", action="append", help="icon JSON (repeat; later files add or override). Default: the kit's icons.json")
    ap.add_argument("--glyphs", action="append", help="glyph JSON (repeat; later files add or override; '' for none). Default: the kit's glyphs.json")
    ap.add_argument("--emoji", default="", help="optional emoji → icon name JSON map")
    ap.add_argument("--global", dest="glob", default="AppIcons", help="global object name in the page (default AppIcons)")
    ap.add_argument("--prefix", default="ci", help="text token prefix, ':<prefix>-name:' (default ci)")
    ap.add_argument("--out", default=str(HERE / "icons.js"), help="output JS file")
    ap.add_argument("--sheet", default="", help="also write a preview HTML sheet here")
    ap.add_argument("--tokens", default="", help="tokens.css path or URL for the sheet (default: the kit's tokens.css)")
    ap.add_argument("--check", action="store_true", help="validate only")
    ap.add_argument("--verbose", action="store_true", help="also list icons with more than 4 facets")
    a = ap.parse_args(argv)
    global VERBOSE
    VERBOSE = a.verbose

    if not re.match(r"^[A-Za-z_$][A-Za-z0-9_$]*$", a.glob):
        raise SystemExit("--global must be a JavaScript identifier")
    if not re.match(r"^[a-z][a-z0-9]*$", a.prefix):
        raise SystemExit("--prefix must be lowercase letters and digits")
    icons = {}
    for src in a.src or [str(HERE / "icons.json")]:
        icons.update(load(src))
    glyphs = {}
    for src in a.glyphs if a.glyphs is not None else [str(HERE / "glyphs.json")]:
        if src:
            glyphs.update(load(src))
    emoji = load(a.emoji) if a.emoji else {}
    errors, warnings = validate(icons, glyphs, emoji)
    for w in warnings:
        print("warning:", w, file=sys.stderr)
    if errors:
        print("\n".join("error: " + e for e in errors), file=sys.stderr)
        raise SystemExit(1)
    if a.check:
        print(f"ok: {len(icons)} icons, {len(glyphs)} glyphs, {len(emoji)} emojis mapped")
        return

    compact = {k: {"p": v["parts"], "l": v.get("lines", [])} for k, v in icons.items()}
    js = (JS.replace("__DATA__", json.dumps(compact, separators=(",", ":")))
            .replace("__GLYPHS__", json.dumps({k: v["svg"] for k, v in glyphs.items()}, separators=(",", ":")))
            .replace("__EMOJI__", json.dumps(emoji, ensure_ascii=False))
            .replace("__GLOBAL__", a.glob).replace("__PREFIX__", a.prefix))
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(js)
    print(f"{out}: {len(icons)} icons, {len(glyphs)} glyphs, {len(emoji)} emojis mapped, {len(js) // 1024} KB, global {a.glob}")

    if a.sheet:
        sheet = Path(a.sheet)
        def rel(p):
            try:
                return str(Path(p).resolve().relative_to(sheet.resolve().parent))
            except ValueError:
                return Path(p).resolve().as_uri()
        tokens = a.tokens or rel(HERE.parent / "tokens.css")
        cells = "".join(
            f'<div class="cell"><div class="row">'
            + "".join(f'<span style="font-size:{s / 1.25}px">:{a.prefix}-{k}:</span>' for s in (16, 24, 48))
            + f'</div><b>{v["label"]}</b><small>{k}</small></div>' for k, v in icons.items())
        gl = "".join(f'<span class="ds-icon-btn" title="{v["label"]}" data-g="{k}"></span>' for k, v in glyphs.items())
        html = (SHEET.replace("__CELLS__", cells).replace("__GLYPHS__", gl).replace("__COUNT__", str(len(icons)))
                .replace("__TOKENS__", tokens).replace("__JS__", rel(out)).replace("__GLOBAL__", a.glob))
        html = html.replace("</body>", f'<script>document.querySelectorAll("[data-g]").forEach(e => e.innerHTML = {a.glob}.glyph(e.dataset.g));</script></body>')
        sheet.parent.mkdir(parents=True, exist_ok=True)
        sheet.write_text(html)
        print(f"{sheet}: preview sheet")


if __name__ == "__main__":
    main()
